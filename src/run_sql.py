"""Run sql/churn_analysis.sql against the predictions table in SQLite and document the results.

    python -m src.run_sql                 # in-memory database
    python -m src.run_sql --db churn.db   # also keep the database file, to open in any SQLite browser

The queries are written in portable SQL (CTEs, window functions, CASE); the only SQLite-specific piece here is the
loader. Each query is tested against an independent pandas calculation in tests/test_sql.py.
"""
from __future__ import annotations

import argparse
import re
import sqlite3
import time
from pathlib import Path

import pandas as pd

from src import config
from src.reporting import md_table

SQL_PATH = config.PROJECT_ROOT / "sql" / "churn_analysis.sql"
TABLE = "customer_predictions"
RESULTS_PATH = config.OUTPUT_DIR / "sql_results.md"


def load_database(csv_path: Path = config.PREDICTIONS_PATH, db_path: str | None = None) -> sqlite3.Connection:
    """Load the predictions CSV into one SQLite table (in memory unless db_path is given)."""
    if not Path(csv_path).exists():
        raise FileNotFoundError(f"{csv_path} not found. Run `python -m src.predict` first.")
    conn = sqlite3.connect(db_path or ":memory:")
    pd.read_csv(csv_path).to_sql(TABLE, conn, index=False, if_exists="replace")
    conn.execute(f"CREATE INDEX IF NOT EXISTS idx_customer ON {TABLE} (CustomerID)")
    return conn


def parse_queries(sql_text: str) -> list[dict]:
    """Split the .sql file into named queries. Each block starts with `-- name: <id>`; `-- question:` and `-- reasoning:` are metadata."""
    parts = re.split(r"^-- name:\s*(\w+)\s*$", sql_text, flags=re.M)
    queries = []
    for name, body in zip(parts[1::2], parts[2::2]):
        question = re.search(r"^-- question:\s*(.+)$", body, flags=re.M)
        reasoning = re.findall(r"^--(?: reasoning:|\s{2,})\s*(.+)$", body, flags=re.M)
        statement = "\n".join(line for line in body.splitlines() if not line.startswith("-- ") and not line.strip() == "--").strip()
        # a block ends at its terminating semicolon; anything after is trailing whitespace or the next section's comments
        statement = statement[: statement.index(";") + 1] if ";" in statement else statement
        queries.append({"name": name, "question": question.group(1).strip() if question else "",
                        "reasoning": " ".join(r.strip() for r in reasoning), "sql": statement})
    return queries


def run_queries(conn: sqlite3.Connection, queries: list[dict]) -> dict[str, pd.DataFrame]:
    return {q["name"]: pd.read_sql_query(q["sql"], conn) for q in queries}


def write_results(queries: list[dict], results: dict[str, pd.DataFrame], path: Path = RESULTS_PATH) -> None:
    lines = ["# SQL analysis results", "",
             "Generated by `python -m src.run_sql` from `sql/churn_analysis.sql`. Every table below is the real output of that query on "
             "`output/customer_churn_predictions.csv`; `tests/test_sql.py` checks each against an independent pandas calculation.", ""]
    for q in queries:
        lines += [f"## {q['name']}", f"**Question:** {q['question']}", "", md_table(results[q["name"]]), ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the churn SQL analysis.")
    parser.add_argument("--db", help="Optional path to keep the SQLite database file.")
    args = parser.parse_args()
    t0 = time.time()
    conn = load_database(db_path=args.db)
    queries = parse_queries(SQL_PATH.read_text(encoding="utf-8"))
    results = run_queries(conn, queries)
    write_results(queries, results)
    print(f"Ran {len(queries)} queries in {time.time() - t0:.1f}s -> {RESULTS_PATH.relative_to(config.PROJECT_ROOT)}")
    sanity = results["q00_sanity_checks"].iloc[0]
    print("sanity checks (all should be 0):", sanity.to_dict())


if __name__ == "__main__":
    main()
