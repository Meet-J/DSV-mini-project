def _fmt(value, pattern: str) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "(blank)"
    return {"0.0%": f"{value:.1%}", "#,0": f"{value:,.0f}", "#,0.00": f"{value:,.2f}", "0.0": f"{value:.1f}"}.get(pattern, str(value))


CONTEXTS = {"No filter": {}, "Contract = Month-to-month": {"Contract": "Month-to-month"},
            "Internet service = Fiber optic": {"InternetService": "Fiber optic"}, "Tenure group = 0-12": {"TenureGroup": "0-12"}}


def expected_values_text(predictions: pd.DataFrame) -> str:
    star = build_star(predictions)
    fact = star["FactCustomer"]
    lines = [
        "# Expected values: how to confirm your Power BI model is right", "",
        "Generated by `python -m src.powerbi_docs`. These numbers come from a pandas replica of the star schema and of every measure, and they agree with the "
        "independent SQL results in `output/sql_results.md` (`tests/test_powerbi.py` enforces this). **They are NOT produced by Power BI**: build the model, then add the "
        "measures to a table or card and compare. A mismatch means a build error (a relationship, a filter, a type), not a different truth.",
        "",
        "## 1. Model integrity (pandas replica)", "",
        md_table(pd.DataFrame(check_integrity(star)).assign(ok=lambda d: d.ok.map({True: "pass", False: "FAIL"}))), "",
        "In Power BI: the measure `[Unmapped Customers]` must show 0, and no slicer should show a `(Blank)` entry.", "",
        "## 2. Every measure under four filter contexts",
        "Context = which slicer value is selected (all other slicers cleared). `[Overall Churn Rate]` deliberately ignores the filter.", "",
    ]
    rows = []
    for m in MEASURES:
        if m.evaluator is None:
            continue
        rows.append({"measure": m.name, **{label: _fmt(evaluate_measure(m.name, fact, flt), m.fmt) for label, flt in CONTEXTS.items()}})
    lines += [md_table(pd.DataFrame(rows)), ""]

    lines += ["## 3. Visual-level checks", ""]
    by = lambda col, levels, names: pd.DataFrame([{col: lv, **{n: _fmt(evaluate_measure(n, fact, {col: lv}), next(m.fmt for m in MEASURES if m.name == n)) for n in names}} for lv in levels])
    lines += ["**Page 1 and 2: churn rate by contract** (axis `DimContract[Contract]`)", "",
              md_table(by("Contract", ["Month-to-month", "One year", "Two year"], ["Total Customers", "Churned Customers", "Churn Rate"])), ""]
    lines += ["**Page 1: active customers by risk tier** (axis `DimRiskCategory[RiskCategory]`)", "",
              md_table(by("RiskCategory", ["Low", "Medium", "High"], ["Active Customers", "Active Monthly Charges", "Expected Revenue at Risk"])), ""]
    internet = fact[fact.InternetService != "No"]
    addons = pd.DataFrame([{"ProtectiveAddOnCount": n, "Total Customers": len(g), "Churn Rate": f"{g.ChurnFlag.mean():.1%}"} for n, g in internet.groupby("ProtectiveAddOnCount")])
    lines += ["**Page 2: churn rate by protective add-ons** (visual filter: internet service is not No)", "", md_table(addons), ""]
    bins = fact[fact.ChurnFlag == 0].groupby(["ProbabilityBinStart", "ProbabilityBin"]).size().reset_index(name="Active Customers").sort_values("ProbabilityBinStart")
    lines += ["**Page 3: distribution of churn probability** (active customers, axis `FactCustomer[ProbabilityBin]`)", "", md_table(bins[["ProbabilityBin", "Active Customers"]]), ""]
    seg_rows = []
    for seg in [s for s in DIMENSIONS["DimRetentionSegment"].frame().RetentionSegment if s != "Already churned"]:
        f = {"RetentionSegment": seg}
        seg_rows.append({"RetentionSegment": seg, "Active Customers": _fmt(evaluate_measure("Active Customers", fact, f), "#,0"),
                         "Active Monthly Charges": _fmt(evaluate_measure("Active Monthly Charges", fact, f), "#,0"),
                         "Average Churn Probability (Active)": _fmt(evaluate_measure("Average Churn Probability (Active)", fact, f), "0.0%"),
                         "Expected Revenue at Risk": _fmt(evaluate_measure("Expected Revenue at Risk", fact, f), "#,0")})
    lines += ["**Page 4: segment table** (rows `DimRetentionSegment[RetentionSegment]`)", "", md_table(pd.DataFrame(seg_rows)), ""]
    drivers = (fact[(fact.ChurnFlag == 0) & fact.RiskCategory.isin(["Medium", "High"])].groupby("TopRiskDriverFeature").size()
               .sort_values(ascending=False).rename("At-Risk Customers").reset_index())
    lines += ["**Page 4: main risk driver** (axis `FactCustomer[TopRiskDriverFeature]`, measure `[At-Risk Customers]`)", "", md_table(drivers), ""]
    top = fact[fact.ChurnFlag == 0].sort_values(["ExpectedMonthlyRevenueAtRisk", "CustomerID"], ascending=[False, True]).head(5)
    lines += ["**Page 4: top 5 of the priority list** (Top N 10 by `[Expected Revenue at Risk]`)", "",
              md_table(top[["CustomerID", "RetentionSegment", "ExpectedMonthlyRevenueAtRisk", "TopRiskDriver1"]].rename(columns={"ExpectedMonthlyRevenueAtRisk": "Expected Revenue at Risk"})), ""]
    return "\n".join(lines)


# ----------------------------------------------------------------------------------------------
def main() -> None:
    predictions = pd.read_csv(config.PREDICTIONS_PATH)
    (POWERBI_DIR / "wireframes").mkdir(parents=True, exist_ok=True)
    (POWERBI_DIR / "dax_measures.dax").write_text(dax_text(), encoding="utf-8")
    (POWERBI_DIR / "power_query.m").write_text(power_query_text(), encoding="utf-8")
    (POWERBI_DIR / "dashboard_spec.md").write_text(spec_text(), encoding="utf-8")
    (POWERBI_DIR / "data_model.md").write_text(data_model_text(predictions), encoding="utf-8")
    (POWERBI_DIR / "expected_values.md").write_text(expected_values_text(predictions), encoding="utf-8")
    for i, page in enumerate(PAGES, 1):
        slug = re.sub(r"[^a-z0-9]+", "_", page.name.lower()).strip("_")
        draw_wireframe(page, POWERBI_DIR / "wireframes" / f"page{i}_{slug}.png")
    print(f"Wrote {len(MEASURES)} measures, {len(DIMENSIONS) + 2} Power Query queries, {len(PAGES)} page specs and wireframes to powerbi/")


if __name__ == "__main__":
    main()
