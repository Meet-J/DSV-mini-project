def data_model_text(predictions: pd.DataFrame) -> str:
    star = build_star(predictions)
    tables = [{"table": "FactCustomer", "role": "Fact", "primary key": "CustomerID", "rows": f"{len(star['FactCustomer']):,}",
               "grain": "one row per customer at the snapshot date", "columns": len(FACT_COLUMNS)}]
    tables += [{"table": n, "role": "Dimension", "primary key": d.key, "rows": len(d.rows), "grain": "one row per level", "columns": len(d.columns)}
               for n, d in DIMENSIONS.items()]
    rels = [{"from (many side)": f"FactCustomer[{fk}]", "to (one side)": f"{dim}[{fk}]", "cardinality": "many to one (*:1)",
             "filter direction": f"{dim} filters FactCustomer (single)", "active": "yes"} for fk, dim in RELATIONSHIPS]
    sorts = [{"column": f"{n}[{c}]", "sort by column": f"{n}[{o}]"} for n, d in DIMENSIONS.items() for c, o in d.sort_by.items()]
    def _levels(dim_name):                         # actual alphabetical order vs the intended order, computed rather than asserted
        labels = [r[0] for r in DIMENSIONS[dim_name].rows]
        return ", ".join(sorted(labels)), ", ".join(labels)
    alpha_charge, intended_charge = _levels("DimChargeBand")
    alpha_risk, intended_risk = _levels("DimRiskCategory")
    alphabetical_examples = (f"ChargeBand would read {alpha_charge} instead of {intended_charge}, and RiskCategory would read {alpha_risk} instead of {intended_risk}")
    lines = [
        "# Power BI data model", "",
        "Generated by `python -m src.powerbi_docs` from `src/powerbi_model.py`. One source file feeds the model: `output/customer_churn_predictions.csv`.", "",
        "## Shape: a star with one fact table",
        "```",
        "  DimContract    DimInternetService    DimPaymentMethod    DimTenureGroup",
        "          \\               |                  |                /",
        "           \\              |                  |               /",
        "            +-------------+------------------+--------------+",
        "                          |   FactCustomer   |",
        "            +-------------+------------------+--------------+",
        "           /              |                  |               \\",
        "          /               |                  |                \\",
        "  DimChargeBand   DimRiskCategory   DimCustomerStatus   DimRetentionSegment",
        "```", "",
        "## Tables", "", md_table(pd.DataFrame(tables)), "",
        "## Relationships",
        "Every relationship is many-to-one, filters flow from the dimension to the fact only, and none is bidirectional. A text key is used because the dimensions have "
        "3 to 7 rows; surrogate integer keys would add no benefit at this size.", "", md_table(pd.DataFrame(rels)), "",
        "## Sort-by columns",
        "Set under Column tools > Sort by column. Without them Power BI sorts text alphabetically: " + alphabetical_examples + ".", "",
        md_table(pd.DataFrame(sorts)), "",
        "## Hide in Report view",
        "- On FactCustomer, the eight key columns: " + ", ".join(f"`{c}`" for c in HIDDEN_FACT_COLUMNS) + ". Visuals use the dimension's column instead (that is what makes the dimension, not the fact, the filter source).",
        "- On every dimension, the `...Order` columns, `ColorHex` and `Definition` (they are used by sorting and by `[Risk Color]`, not shown).",
        "- `FactCustomer[ProbabilityBinStart]` (used only to sort and colour the histogram).", "",
        "## Design decisions",
        "- **Snapshot grain.** The data has no dates, so there is no date table and no time intelligence. 'Trend' views use tenure cohorts instead.",
        "- **Yes/No attributes stay on the fact** (SeniorCitizen, Partner, add-ons, and so on). A two-row dimension adds a relationship but no analytical value.",
        "- **Risk and revenue measures use active customers only**, defined once in `[Active Customers]` and `[Active Monthly Charges]` so no measure can forget the filter.",
        "- **Measures live in an empty `_Measures` table**, created with Enter data, so they stay together and are not tied to a data table.",
        "- **Measures, not calculated columns,** for everything that aggregates: they respond to slicers and cost no memory per row.", "",
    ]
    return "\n".join(lines)

