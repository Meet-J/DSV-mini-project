KIND_STYLE = {"text": ("#FFFFFF", "#B8C2CF", "#262626"), "slicer": ("#E8EDF2", "#B8C2CF", "#262626"), "card": (DARK, DARK, "#FFFFFF"),
              "bar": ("#FFFFFF", SLATE, "#262626"), "column": ("#FFFFFF", SLATE, "#262626"), "stacked_column": ("#FFFFFF", SLATE, "#262626"),
              "table": ("#F4F6F9", SLATE, "#262626"), "matrix": ("#F4E3E1", ACCENT, "#262626")}


def draw_wireframe(page, path) -> None:
    fig, ax = plt.subplots(figsize=(CANVAS_W / 100, CANVAS_H / 100), dpi=100)
    ax.set_xlim(0, CANVAS_W); ax.set_ylim(CANVAS_H, 0); ax.axis("off")
    ax.add_patch(Rectangle((0, 0), CANVAS_W, CANVAS_H, facecolor="#FAFAFA", edgecolor="#999999", lw=1))
    for v in page.visuals:
        face, edge, ink = KIND_STYLE[v.kind]
        ax.add_patch(Rectangle((v.x, v.y), v.w, v.h, facecolor=face, edgecolor=edge, lw=1.4))
        size = 15 if v.kind == "text" and v.id.endswith("_title") else 9 if v.h >= 90 else 8
        chars = max(10, int(v.w / (size * 0.95)))                       # wrap to the box width: matplotlib's own wrap ignores data coordinates
        body = textwrap.fill(v.title, width=chars)
        label = body if v.kind == "text" else f"{body}\n[{v.kind.replace('_', ' ')}]"
        ax.text(v.x + v.w / 2, v.y + v.h / 2, label, ha="center", va="center", fontsize=size, color=ink,
                fontweight="bold" if v.id.endswith("_title") else "normal")
    ax.set_title(f"Wireframe: {page.name}" + ("  (hidden drill-through page)" if page.hidden else "") + f"   |   {CANVAS_W} x {CANVAS_H} px canvas",
                 loc="left", fontsize=10, color="#555555")
    fig.savefig(path, bbox_inches="tight"); plt.close(fig)


