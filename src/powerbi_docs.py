# Power Query (M)
# ----------------------------------------------------------------------------------------------
def _m_value(v) -> str:
    return '"' + v.replace('"', '""') + '"' if isinstance(v, str) else str(v)


def power_query_text() -> str:
    types = {c: ("Int64.Type" if c in INT_COLUMNS else "type number" if c in NUMBER_COLUMNS else "type text") for c in CSV_COLUMNS}
    type_rows = ",\n".join(f'            {{"{c}", {t}}}' for c, t in types.items())
    out = [
        "// =====================================================================================================",
        "// Power Query (M) for the churn dashboard. Generated by `python -m src.powerbi_docs`.",
        "//",
        "// Create one blank query per section below (Home > Transform data > New source > Blank query), open Advanced Editor,",
        "// paste the code, and rename the query to the name in the section heading. Untick 'Enable load' on Customers_Raw.",
        "//",
        "// The star schema is built from ONE file: output/customer_churn_predictions.csv, produced by `python -m src.predict`.",
        "// Dimensions are static lists on purpose: they fix the order and labels, and include every level even if it has no customers.",
        "// NOTE: this M was written without access to Power BI Desktop and has not been run. See BUILD_GUIDE.md, step 3, for the check.",
        "// =====================================================================================================",
        "",
        "// ===== Parameter: DataPath =====",
        "// Home > Transform data > Manage parameters > New parameter. Name: DataPath. Type: Text. Current value: the full path to the CSV,",
        "// for example C:\\Users\\you\\customer-churn-prediction-powerbi\\output\\customer_churn_predictions.csv",
        "// Power Query has no relative paths, so a parameter is how the file location stays out of the queries. Change it once to repoint everything.",
        '"C:\\path\\to\\customer-churn-prediction-powerbi\\output\\customer_churn_predictions.csv" meta [IsParameterQuery = true, Type = "Text", IsParameterQueryRequired = true]',
        "",
        "// ===== Query: Customers_Raw  (staging only: untick Enable load) =====",
        "let",
        '    Source = Csv.Document(File.Contents(DataPath), [Delimiter = ",", Encoding = 65001, QuoteStyle = QuoteStyle.Csv]),',
        "    PromotedHeaders = Table.PromoteHeaders(Source, [PromoteAllScalars = true]),",
        "    // The culture argument fixes the decimal separator, so the file loads the same on any regional setting.",
        "    TypedColumns = Table.TransformColumnTypes(",
        "        PromotedHeaders,",
        "        {",
        type_rows,
        "        },",
        '        "en-US"',
        "    )",
        "in",
        "    TypedColumns",
        "",
        "// ===== Query: FactCustomer =====",
        "// Grain: one row per customer. Adds three columns for the visuals and drops the order columns, which live on the dimensions.",
        "let",
        "    Source = Customers_Raw,",
        "    // TopRiskDriver1 reads 'feature = value'; cutting at ' = ' groups drivers by feature (tenure = 1 and tenure = 2 become one: tenure).",
        '    AddDriverFeature = Table.AddColumn(Source, "TopRiskDriverFeature", each if [TopRiskDriver1] = null then null else Text.BeforeDelimiter([TopRiskDriver1], " = "), type text),',
        "    // Probability in 5-point bins for the histogram. The top bin is capped so a probability of exactly 1.0 stays in 95-100.",
        '    AddBinStart = Table.AddColumn(AddDriverFeature, "ProbabilityBinStart", each Number.Min(Number.RoundDown([ChurnProbability] * 20, 0), 19) / 20, type number),',
        '    AddBinLabel = Table.AddColumn(AddBinStart, "ProbabilityBin", each Text.From(Number.Round([ProbabilityBinStart] * 100, 0)) & "-" & Text.From(Number.Round([ProbabilityBinStart] * 100, 0) + 5) & "%", type text),',
        "    RemoveOrderColumns = Table.RemoveColumns(AddBinLabel, {" + ", ".join(f'"{c}"' for c in ORDER_COLUMNS_MOVED_TO_DIMENSIONS) + "})",
        "in",
        "    RemoveOrderColumns",
        "",
    ]
    for name, dim in DIMENSIONS.items():
        col_types = ", ".join(f"{c} = {'Int64.Type' if isinstance(v, int) else 'text'}" for c, v in zip(dim.columns, dim.rows[0]))
        rows = ",\n".join("            {" + ", ".join(_m_value(v) for v in row) + "}" for row in dim.rows)
        out += [f"// ===== Query: {name} =====", "let", "    Source = #table(", f"        type table [{col_types}],", "        {", rows, "        }", "    )", "in", "    Source", ""]
    return "\n".join(out)


