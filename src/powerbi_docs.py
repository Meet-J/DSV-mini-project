def dax_text() -> str:
    lines = [
        "// =====================================================================================================",
        "// DAX measures for the churn dashboard. Generated by `python -m src.powerbi_docs` from src/powerbi_model.py.",
        "//",
        "// How to add them: Modeling > New measure, paste one definition at a time (or paste several into Tabular Editor).",
        "// Recommended: create an empty table called _Measures (Home > Enter data, one blank column, then hide the column)",
        "// and create every measure there, so they sit together in one folder. Set the Display folder and Format shown",
        "// above each definition. Measures reference tables by name, so they work wherever they are stored.",
        "// =====================================================================================================",
        "",
    ]
    folder = None
    for m in MEASURES:
        if m.folder != folder:
            folder = m.folder
            lines += ["", f"// ------------------------------------ {folder} ------------------------------------", ""]
        expr = m.dax.replace(" || ", "\n        || ") if m.name == "Unmapped Customers" else m.dax
        lines += [f"// {m.description}", f"// Display folder: {m.folder}" + (f" | Format: {m.fmt}" if m.fmt else ""), f"{m.name} =", f"    {expr}", ""]
    return "\n".join(lines)


